const text = t => ({ type: 'text', text: t })
const user = (...blocks) => ({ role: 'user', content: blocks.map(b => (typeof b === 'string' ? text(b) : b)) })
const optionsBlock = obj => `\`\`\`dsh-audio-options\n${JSON.stringify(obj)}\n\`\`\``
// Exactly what dsh-agent model-selection appends after the prompt on the first request after a switch.
const modelChanged = (from, to) => createUserMessage({
  content: [text(`[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]`)],
  source: { kind: 'plugin', plugin: 'model-selection', form: 'notice', summary: { text: `${from} → ${to}` } },
})
// The I3-VOX server error (vLLM 0.29.0, Voxtral Mini 3B 2507), verbatim.
const VOXTRAL_400 = 'Found system messages at indexes [0] and audio chunks in messages at indexes [1]. This is not allowed prior to the tokenizer version 13.'

async function multiStore(files) {
  const stores = await Promise.all(files.map(([bytes, name]) => fakeStore(bytes, name)))
  const byName = n => stores.find(s => s.ref.name === n)
  return {
    refs: stores.map(s => s.ref),
    handle: n => text(fileHandleText(byName(n).ref, byName(n).path)),
    store: { fileHostPath: r => byName(r.name).path, async * readFileStream(r) { yield * byName(r.name).store.readFileStream(r) } },
  }
}

async function plugin(routes, store) {
  const outputDir = await tempDir('dgx-042-')
  const p = createAudioPlugin({ rowConfig: { outputDir, hubLimits: { pingMs: 60_000 }, routes }, log: () => {}, attachments: () => store })
  const readLog = async () => (await readFile(p.config().invocationLog, 'utf8')).trim().split('\n').map(l => JSON.parse(l))
  return { p, readLog }
}

/** Chat server that rejects a system message together with audio, like vLLM's Mistral tokenizer mode (< v13). */
function mistralLikeChat() {
  return scriptedServer(async (req, res, call) => {
    const messages = call.json.messages
    const hasAudio = messages.some(m => Array.isArray(m.content) && m.content.some(p => p.type === 'input_audio'))
    if (hasAudio && messages.some(m => m.role === 'system')) {
      res.writeHead(400, { 'content-type': 'application/json' })
      res.end(JSON.stringify({ error: { message: VOXTRAL_400, type: 'BadRequestError', code: 400 } }))
      return
    }
    res.writeHead(200, { 'content-type': 'application/json' })
    res.end(JSON.stringify({ choices: [{ index: 0, message: { content: 'The speaker asks the audience what they can do for their country.' }, finish_reason: 'stop' }] }))
  })
}

test('I3-VOX c3: Voxtral-Mini-3B-2507 chat with audio folds the system prompt by verified rule (product default path)', async (tc) => {
  const server = await mistralLikeChat()
  tc.after(() => server.close())
  const fx = await multiStore([[wav(0.5), 'jfk.wav']])
  const { p, readLog } = await plugin([{ provider: 'vox', displayName: 'Voxtral', baseURL: server.url, models: [{ id: 'voxtral-chat', upstreamModel: 'mistralai/Voxtral-Mini-3B-2507', streaming: { text: 'off' } }] }], fx.store)
  const chunks = await collect(p.adapter.stream({ provider: 'vox', model: 'voxtral-chat', system: 'You are a helpful assistant.', messages: [user(fx.handle('jfk.wav'), 'What does the speaker ask?')] }))
  assert.equal(server.calls.length, 1, 'no failed first attempt')
  const sent = server.calls[0].json.messages
  assert.equal(sent.some(m => m.role === 'system'), false)
  assert.match(sent[0].content.find(c => c.type === 'text').text, /^You are a helpful assistant\.\n\n/)
  assert.ok(chunks.some(c => c.type === 'block-end'))
  const log = (await readLog()).at(-1)
  assert.deepEqual([log.request.systemPlacement, log.request.systemPlacementReason], ['user-prefix', 'model-rule:voxtral-mini-3b-2507'])
})

test('auto on an unlisted model: one retry on the exact server rejection, remembered per deployment; explicit settings win; other 400s never retry', async (tc) => {
  const server = await mistralLikeChat()
  tc.after(() => server.close())
  const fx = await multiStore([[wav(0.5), 'clip.wav']])
  const route = models => [{ provider: 'm', displayName: 'M', baseURL: server.url, models }]
  const ask = (p, model) => collect(p.adapter.stream({ provider: 'm', model, system: 'Be brief.', messages: [user(fx.handle('clip.wav'), 'Summarize.')] }))

  const auto = await plugin(route([{ id: 'small', upstreamModel: 'mistralai/Voxtral-Small-24B-2507', streaming: { text: 'off' } }]), fx.store)
  await ask(auto.p, 'small')
  assert.deepEqual(server.calls.map(c => c.json.messages.some(m => m.role === 'system')), [true, false], 'system first, then folded retry')
  let log = (await auto.readLog()).at(-1)
  assert.deepEqual([log.request.systemPlacementReason, log.retriedWithUserPrefix], ['server-rejected-system-with-audio', true])
  await ask(auto.p, 'small')
  assert.equal(server.calls.length, 3, 'second request goes straight to user-prefix')
  log = (await auto.readLog()).at(-1)
  assert.equal(log.request.systemPlacementReason, 'observed:server-rejected-system-with-audio')

  server.calls.length = 0
  const explicit = await plugin(route([{ id: 'vox-sys', upstreamModel: 'mistralai/Voxtral-Mini-3B-2507', systemPromptWithAudio: 'system', streaming: { text: 'off' } }]), fx.store)
  await assert.rejects(ask(explicit.p, 'vox-sys'), e => e.code === 'INVALID_REQUEST' && /tokenizer version 13/.test(e.message) && /systemPromptWithAudio: "user-prefix"/.test(e.message))
  assert.equal(server.calls.length, 1, 'explicit system is honored: no silent retry')

  server.calls.length = 0
  const prefix = await plugin(route([{ id: 'generic', upstreamModel: 'org/any-audio-llm', systemPromptWithAudio: 'user-prefix', streaming: { text: 'off' } }]), fx.store)
  await ask(prefix.p, 'generic')
  assert.equal(server.calls[0].json.messages.some(m => m.role === 'system'), false)
  assert.equal((await prefix.readLog()).at(-1).request.systemPlacementReason, 'config')

  // Not a global policy: other models keep the system message; text-only requests keep it even on Voxtral.
  server.calls.length = 0
  const other = await plugin(route([{ id: 'qwen', upstreamModel: 'Qwen/Qwen2-Audio-7B-Instruct', streaming: { text: 'off' } }, { id: 'vox', upstreamModel: 'mistralai/Voxtral-Mini-3B-2507', streaming: { text: 'off' } }]), fx.store)
  await collect(other.p.adapter.stream({ provider: 'm', model: 'vox', system: 'Be brief.', messages: [user('No audio here.')] }))
  assert.equal(server.calls[0].json.messages[0].role, 'system')

  const accepting = await scriptedServer(async (req, res) => { res.writeHead(200, { 'content-type': 'application/json' }); res.end(JSON.stringify({ choices: [{ index: 0, message: { content: 'ok' }, finish_reason: 'stop' }] })) })
  tc.after(() => accepting.close())
  const qwen = await plugin([{ provider: 'm', displayName: 'M', baseURL: accepting.url, models: [{ id: 'qwen', upstreamModel: 'Qwen/Qwen2-Audio-7B-Instruct', streaming: { text: 'off' } }] }], fx.store)
  await ask(qwen.p, 'qwen')
  assert.deepEqual([accepting.calls[0].json.messages[0].role, (await qwen.readLog()).at(-1).request.systemPlacementReason], ['system', 'auto:default'], 'audio + system stays a system message for other models')

  const plain400 = await scriptedServer(async (req, res) => { res.writeHead(400, { 'content-type': 'application/json' }); res.end('{"error":{"message":"max_tokens is too large"}}') })
  tc.after(() => plain400.close())
  const p4 = await plugin([{ provider: 'm', displayName: 'M', baseURL: plain400.url, models: [{ id: 'x', upstreamModel: 'org/x', streaming: { text: 'off' } }] }], fx.store)
  await assert.rejects(ask(p4.p, 'x'), /max_tokens/)
  assert.equal(plain400.calls.length, 1)
  // Settings/row configs that never mention it resolve to auto.
  assert.equal(resolveConfig({ routes: route([{ id: 'z' }]) }).routes[0].models[0].systemPromptWithAudio, 'auto')
})

test('Harness "[model changed: …]" notice after the prompt: transcribe and speech text/options/reference read the pending turn', async (tc) => {
  const asr = await scriptedServer(async (req, res) => { res.writeHead(200, { 'content-type': 'application/json' }); res.end('{"text":"ask not what your country can do for you"}') })
  tc.after(() => asr.close())
  const header = wavHeader({ encoding: 'pcm_s16le', sampleRate: 24000, channels: 1 }, 2400)
  const tts = await scriptedServer(async (req, res) => { res.writeHead(200, { 'content-type': 'audio/wav' }); res.end(Buffer.concat([header, pcm16(0.05, 24000)])) })
  tc.after(() => tts.close())
  const fx = await multiStore([[wav(0.4, 16000, 300), 'question.wav'], [wav(0.3, 16000, 900), 'reference-voice-1.wav']])
  const { p } = await plugin([
    { provider: 'a', displayName: 'A', baseURL: asr.url, models: [{ id: 'asr', mode: 'transcribe', streaming: { text: 'off' } }] },
    { provider: 't', displayName: 'T', baseURL: tts.url, models: [{ id: 'clone', mode: 'speech', streaming: { audio: 'off' }, speech: { refAudio: 'attachment' } }] },
  ], fx.store)
  const notice = modelChanged('voxtral-chat', 'asr')

  await collect(p.adapter.stream({ provider: 'a', model: 'asr', messages: [user(fx.handle('question.wav'), 'Transcribe this.'), notice] }))
  assert.equal(asr.calls.length, 1, 'transcribed despite the trailing notice (0.4.1: NO_AUDIO_INPUT)')

  await collect(p.adapter.stream({ provider: 't', model: 'clone', messages: [user(fx.handle('reference-voice-1.wav'), `${optionsBlock({ v: 1, voice: 'ryan', referenceAudio: 'reference-voice-1.wav' })}\nSay hello to the museum visitors.`), notice] }))
  const body = tts.calls[0].json
  assert.equal(body.input, 'Say hello to the museum visitors.', 'speaks the prompt, not the notice')
  assert.equal(body.voice, 'ryan', 'options block of the prompt still applies')
  assert.ok(body.ref_audio.startsWith('data:audio/wav;base64,'))

  // Same notice without a source tag (e.g. restored history) is recognized by its exact text.
  await collect(p.adapter.stream({ provider: 't', model: 'clone', messages: [user('Second line to read.'), user('[model changed: assistant turns above this point were generated by a; the session continues with clone]')] }))
  assert.equal(tts.calls[1].json.input, 'Second line to read.')

  // Audio before the last assistant message is not the pending turn.
  await assert.rejects(collect(p.adapter.stream({ provider: 'a', model: 'asr', messages: [user(fx.handle('question.wav')), { role: 'assistant', content: [text('done')] }, user('and now?'), notice] })), e => e.code === 'NO_AUDIO_INPUT')
})

