test('per-turn speech fields of /v1/audio/speech: speed/seed/sample_rate/extra_params/ambient_sound/duration, ref_audio list, ref_audio_2, emotion clip, word_timestamps', async (tc) => {
  const header = wavHeader({ encoding: 'pcm_s16le', sampleRate: 24000, channels: 1 }, 4800)
  const server = await scriptedServer(async (req, res, call) => {
    const headers = { 'content-type': 'audio/wav' }
    if (call.json.word_timestamps) headers['x-word-timestamps'] = JSON.stringify([{ word: 'Hello', start_ms: 0, end_ms: 320 }, { word: 'world', start_ms: 340, end_ms: 700 }])
    res.writeHead(200, headers)
    res.end(Buffer.concat([header, pcm16(0.1, 24000)]))
  })
  tc.after(() => server.close())
  const fx = await multiStore([[wav(0.2, 16000, 200), 'speaker-a.wav'], [wav(0.2, 16000, 500), 'speaker-b.wav'], [wav(0.2, 16000, 800), 'angry.wav']])
  const { p, readLog } = await plugin([{ provider: 's', displayName: 'S', baseURL: server.url, models: [
    { id: 'ttsd', mode: 'speech', streaming: { audio: 'auto' }, speech: { refAudio: 'attachment' } },
    { id: 'sfx', mode: 'speech', streaming: { audio: 'off' } },
  ] }], fx.store)
  const run = (model, blocks) => collect(p.adapter.stream({ provider: 's', model, sessionId: 's', messages: [user(...blocks)] }))

  await run('ttsd', [fx.handle('speaker-a.wav'), fx.handle('speaker-b.wav'), fx.handle('angry.wav'),
    `${optionsBlock({ v: 1, speed: 1.25, seed: 7, sampleRate: 24000, extraParams: { emo_alpha: 0.6, lang: 'en' }, referenceAudio: 'speaker-a.wav', referenceAudio2: 'speaker-b.wav', emotionAudio: 'angry.wav', wordTimestamps: true })}\n[S1] Hello [S2] world`])
  const b = server.calls[0].json
  assert.deepEqual([b.speed, b.seed, b.sample_rate, b.word_timestamps, b.input], [1.25, 7, 24000, true, '[S1] Hello [S2] world'])
  assert.equal(b.stream, undefined, 'word_timestamps forces a non-streaming request (server rejects it with stream=true)')
  assert.deepEqual([b.extra_params.emo_alpha, b.extra_params.lang], [0.6, 'en'])
  const decode = d => Buffer.from(d.split(',')[1], 'base64')
  assert.ok(decode(b.ref_audio).equals(wav(0.2, 16000, 200)))
  assert.ok(decode(b.ref_audio_2).equals(wav(0.2, 16000, 500)))
  assert.ok(decode(b.extra_params.emo_audio).equals(wav(0.2, 16000, 800)))
  const log = (await readLog()).at(-1)
  assert.equal(typeof log.request.body.ref_audio_2.sha256, 'string', 'clips are logged by hash, not inlined')
  assert.deepEqual(log.request.body.extra_params.emo_audio.name, 'angry.wav')

  // Ming-omni-tts podcast mode: ref_audio as a list of clips.
  await run('ttsd', [fx.handle('speaker-a.wav'), fx.handle('speaker-b.wav'), `${optionsBlock({ v: 1, referenceAudio: ['speaker-a.wav', 'speaker-b.wav'], referenceText: 'a|b', xVectorOnlyMode: false })}\nTwo hosts talk.`])
  assert.equal(Array.isArray(server.calls[1].json.ref_audio) && server.calls[1].json.ref_audio.length, 2)
  assert.equal(server.calls[1].json.x_vector_only_mode, false)

  // MOSS-SoundEffect: description in ambient_sound, empty input allowed.
  await run('sfx', [optionsBlock({ v: 1, ambientSound: 'ocean waves on a rocky beach', durationSeconds: 5 })])
  assert.deepEqual([server.calls[2].json.input, server.calls[2].json.ambient_sound, server.calls[2].json.duration_seconds], ['', 'ocean waves on a rocky beach', 5])

  // Word timestamps surface in the result block.
  const chunks = await run('ttsd', [fx.handle('speaker-a.wav'), `${optionsBlock({ v: 1, wordTimestamps: true })}\nHello world`])
  const final = chunks.filter(c => c.type === 'block-end').map(c => c.block.text).join('\n')
  const id = /\/api\/dsh-dgx-audio\/v1\/result\?id=([A-Za-z0-9._~-]+)\)/.exec(final)[1] // 0.4.3 link-line carrier
  const result = await (await p.routes().find(r => r.path.endsWith('/result')).fetch(new Request(`http://h/api/dsh-dgx-audio/v1/result?id=${id}`))).json()
  assert.deepEqual(result.wordTimestamps, { state: 'aligned', words: [{ word: 'Hello', startMs: 0, endMs: 320 }, { word: 'world', startMs: 340, endMs: 700 }] })

  await assert.rejects(run('sfx', [`${optionsBlock({ speed: 0.1 })}\nx`]), e => e.code === 'INVALID_REQUEST' && /speed/.test(e.message))
  await assert.rejects(run('sfx', [`${optionsBlock({ seed: 1.5 })}\nx`]), /seed/)
  await assert.rejects(run('sfx', [`${optionsBlock({ referenceAudio2: 'missing.wav' })}\nx`]), /not part of this message/)
  const doc = p.routes().find(r => r.path.endsWith('/capabilities'))
  const params = (await (await doc.fetch(new Request('http://h/api/dsh-dgx-audio/v1/capabilities'))).json()).routes[0].models[0].params
  assert.deepEqual(params.find(x => x.key === 'speed'), { key: 'speed', type: 'number', min: 0.25, max: 4 })
  assert.deepEqual(params.find(x => x.key === 'seed'), { key: 'seed', type: 'number', step: 1 })
  assert.equal(params.find(x => x.key === 'voice').source, 'voices')
})

test('speech stream-input: per-chunk sample_rate wins over the nominal audio.start 24000; binary frames use an explicit configured rate', async (tc) => {
  const server = await wsServer((conn) => {
    conn.onMessage(async (m) => {
      if (m.type !== 'input.done') return
      conn.send({ type: 'audio.start', utterance_index: 0, sentence_index: 0, sentence_text: 'Hi.', format: 'pcm', sample_rate: 24000 })
      if (conn.url.pathname.includes('json')) {
        conn.send({ type: 'audio.chunk', utterance_index: 0, sentence_index: 0, chunk_id: 0, sample_rate: 48000, audio_b64: pcm16(0.1, 48000).toString('base64'), timestamps: null })
      } else {
        conn.sendBinary(pcm16(0.1, 22050))
      }
      await sleep(50)
      conn.send({ type: 'audio.done', utterance_index: 0, sentence_index: 0 })
      conn.send({ type: 'session.done', utterance_index: 0, total_sentences: 1 })
    })
  })
  tc.after(() => server.close())
  const outputDir = await tempDir('dgx-042-ws-')
  const p = createAudioPlugin({ rowConfig: { outputDir, hubLimits: { pingMs: 60_000 }, routes: [{ provider: 'w', displayName: 'W', baseURL: server.baseURL, models: [
    { id: 'json48k', mode: 'realtime', realtime: { wire: 'omni-speech-ws', path: '/json/audio/speech/stream' } },
    { id: 'bin22k', mode: 'realtime', realtime: { wire: 'omni-speech-ws', outputSampleRate: 22050 } },
  ] }] }, log: () => {} })
  const events = []
  const ac = new AbortController()
  const reading = (async () => { try { for await (const e of p.hub.subscribe('s', { signal: ac.signal })) events.push(e) } catch { /* aborted */ } })()
  const post = async (path, body) => (await p.routes().find(r => r.path === path.split('?')[0]).fetch(new Request(`http://h${path}`, { method: 'POST', body: JSON.stringify(body) }))).json()
  for (const model of ['json48k', 'bin22k']) {
    const opened = await post('/api/dsh-dgx-audio/v1/live/open', { sessionId: 's', provider: 'w', model })
    await post(`/api/dsh-dgx-audio/v1/live/text?liveId=${opened.liveId}`, { text: 'Hi.', done: true })
    await sleep(250)
    await post(`/api/dsh-dgx-audio/v1/live/close?liveId=${opened.liveId}`, {})
  }
  ac.abort()
  await reading
  const rates = events.filter(e => e.type === 'audio.format').map(e => e.sampleRate)
  assert.deepEqual(rates, [48000, 22050])
  const ends = events.filter(e => e.type === 'audio.end')
  assert.deepEqual(ends.map(e => e.totalSamples), [4800, 2205])
  p.dispose()
})
